#!/usr/bin/env python3
"""Turn tools/score_regions.py's region-weights.json into the app's table.

Writes Packages/WeatherCore/blend-regions.json (the plain table, easy to read from any app,
the Android port included) and Packages/WeatherCore/Sources/WeatherCore/BlendRegionTable.swift
(the same numbers as Swift). A test checks the two match.

  python3 gen_blend_regions.py region-weights.json
"""
import json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Packages", "WeatherCore")
ORDER = ["germany", "europeAI", "europe", "uk", "canada", "canadaHighRes", "us", "usHighRes"]


def day(d):
    items = sorted(d.items(), key=lambda kv: (-kv[1], ORDER.index(kv[0])))
    return "[" + ", ".join(f".{m}: {w}" for m, w in items) + "]"


def region(r, indent):
    boxes = ", ".join("Box(" + ", ".join(f"{x}" for x in b) + ")" for b in r.get("boxes", []))
    days = "".join(f"{indent}        {day(d)},\n" for d in r["byDay"])
    return (f'BlendRegion(\n{indent}    id: "{r["id"]}", name: "{r["name"]}",\n'
            f'{indent}    boxes: [{boxes}],\n'
            f'{indent}    useBlend: {"true" if r["useBlend"] else "false"},\n'
            f'{indent}    byDay: [\n{days}{indent}    ])')


def main():
    src = json.load(open(sys.argv[1]))
    table = {"regions": [{k: r[k] for k in ("id", "name", "boxes", "useBlend", "byDay")} for r in src["regions"]],
             "global": {"id": "global", "name": "Elsewhere", "boxes": [],
                        "useBlend": src["global"]["useBlend"], "byDay": src["global"]["byDay"]}}
    with open(os.path.join(ROOT, "blend-regions.json"), "w") as f:
        json.dump(table, f, indent=1)
        f.write("\n")
    regions = ",\n        ".join(region(r, "        ") for r in table["regions"])
    swift = f"""// Generated by tools/gen_blend_regions.py from tools/score_regions.py's results. Don't edit by
// hand: re-run the scorer (Actions: "Score models by region") and the generator. The same table
// is in Packages/WeatherCore/blend-regions.json.

extension BlendRegion {{
    /// Regions in lookup order: the first whose box holds the spot wins.
    static let regions: [BlendRegion] = [
        {regions},
    ]

    /// Everywhere else.
    static let fallback = {region(table["global"], "    ")}
}}
"""
    with open(os.path.join(ROOT, "Sources", "WeatherCore", "BlendRegionTable.swift"), "w") as f:
        f.write(swift)


if __name__ == "__main__":
    main()
